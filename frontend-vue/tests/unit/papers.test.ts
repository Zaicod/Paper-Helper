import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { createMemoryHistory, createRouter } from 'vue-router'
import CollectionDetailView from '../../src/views/CollectionDetailView.vue'
import { api } from '../../src/api'
import { createPinia } from 'pinia'
import { useAuthStore } from '../../src/stores/auth'

vi.mock('../../src/api', () => ({ api: {
  papers: { search: vi.fn() }, collections: {
    list: vi.fn(), get: vi.fn(), create: vi.fn(), update: vi.fn(), remove: vi.fn(), note: vi.fn(),
    addPaper: vi.fn(), removePaper: vi.fn(), paperNote: vi.fn(), paper: vi.fn(), updatePaper: vi.fn(),
  },
} }))
const paper = { source: 'arxiv', paper_id: '2401.00001', title: 'Evidence retrieval', abstract: 'A source abstract.', authors: ['Smith, Alice'], categories: ['cs.IR'], published: '2026-10-19', page_url: 'https://arxiv.org/abs/2401.00001', pdf_url: null }
const stored = { ...paper, id: 21, added_at: '', note: 'My personal note' }
beforeEach(() => {
  localStorage.clear()
  vi.resetAllMocks()
  vi.mocked(api.collections.list).mockResolvedValue({ collections: [{ id: 7, name: 'Evidence', description: '', paper_count: 1 }], total: 1, page: 0, size: 100 })
  vi.mocked(api.collections.get).mockResolvedValue({ id: 7, name: 'Evidence', description: '', paper_count: 1, overall_note: 'Notebook stays', papers: [stored] })
  vi.mocked(api.collections.paper).mockResolvedValue(stored)
  vi.mocked(api.collections.updatePaper).mockResolvedValue({ ...stored, title: 'My edited title', metadata_edited: true })
  vi.mocked(api.papers.search).mockResolvedValue({ contract_version: 1, query: 'retrieval', requested_source: 'arxiv', used_source: 'arxiv', papers: [paper] })
  vi.mocked(api.collections.addPaper).mockResolvedValue(stored)
})
async function searchPage(userId = 1) {
  const loaded = await import('../../src/views/PaperSearchView.vue').catch(() => null)
  expect(loaded, 'The real-source search page must exist').not.toBeNull()
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/papers', component: loaded!.default }, { path: '/collections', component: { template: '<div />' } }] })
  await router.push('/papers')
  const pinia = createPinia()
  useAuthStore(pinia).user = { id: userId, username: `user${userId}`, email: '', created_at: '' }
  const page = mount(loaded!.default, { global: { plugins: [router, pinia] } })
  await flushPromises()
  return page
}
describe('public paper search and collection editing', () => {
  it('ignores malformed saved conditions and keeps searching when browser storage is blocked', async () => {
    localStorage.setItem('paperflow.search-draft.v1.1', '{broken-json')
    let page = await searchPage()
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(0)
    await page.get('#paper-query').setValue('working search')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).toHaveBeenCalledOnce()
    page.unmount()
    localStorage.clear()
    const denied = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('Storage blocked', 'SecurityError') })
    try {
      page = await searchPage()
      await page.get('#paper-query').setValue('still works')
      expect(page.text()).toContain('无法保存搜索条件')
      await page.get('form').trigger('submit'); await flushPromises()
      expect(api.papers.search).toHaveBeenLastCalledWith('still works', 'auto', 10, 1, 'relevance', [{ text: 'still works', match_mode: 'fuzzy' }])
      page.unmount()
    } finally { denied.mockRestore() }
  })
  it('resets saved conditions when the authenticated account changes while the page is mounted', async () => {
    const page = await searchPage(1)
    await page.get('#paper-query').setValue('first account draft')
    const auth = useAuthStore()
    auth.user = { id: 2, username: 'second', email: '', created_at: '' }
    await flushPromises()
    expect((page.get('#paper-query').element as HTMLInputElement).value).toBe('')
    await page.get('#paper-query').setValue('second account draft')
    auth.user = { id: 1, username: 'first', email: '', created_at: '' }
    await flushPromises()
    expect((page.get('#paper-query').element as HTMLInputElement).value).toBe('first account draft')
    page.unmount()
  })
  it('restores selected keywords, modes, unfinished input and search filters after remount', async () => {
    let page = await searchPage()
    await page.get('#keyword-mode').setValue('exact')
    await page.get('#paper-query').setValue('multimodal learning')
    await page.get('[data-test="add-keyword"]').trigger('click')
    await page.get('#keyword-mode').setValue('fuzzy')
    await page.get('#paper-query').setValue('unfinished draft')
    await page.get('#search-source').setValue('openalex')
    await page.get('#search-sort').setValue('latest')
    await page.get('#search-limit').setValue(20)
    page.unmount()
    page = await searchPage()
    expect(page.get('[data-test="keyword-chip"]').text()).toContain('multimodal learning')
    expect(page.get('[data-test="keyword-chip"]').text()).toContain('精准匹配')
    expect((page.get('#paper-query').element as HTMLInputElement).value).toBe('unfinished draft')
    expect((page.get('#keyword-mode').element as HTMLSelectElement).value).toBe('fuzzy')
    expect((page.get('#search-source').element as HTMLSelectElement).value).toBe('openalex')
    expect((page.get('#search-sort').element as HTMLSelectElement).value).toBe('latest')
    expect((page.get('#search-limit').element as HTMLSelectElement).value).toBe('20')
    expect(api.papers.search).not.toHaveBeenCalled()
    page.unmount()
  })
  it('persists removal and clearing without resurrecting deleted terms', async () => {
    let page = await searchPage()
    for (const text of ['first', 'second']) { await page.get('#paper-query').setValue(text); await page.get('[data-test="add-keyword"]').trigger('click') }
    await page.get('button[aria-label="移除关键词：first"]').trigger('click'); page.unmount()
    page = await searchPage()
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(1)
    expect(page.get('[data-test="keyword-chip"]').text()).toContain('second')
    await page.get('[data-test="clear-keywords"]').trigger('click'); page.unmount()
    page = await searchPage()
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(0)
    page.unmount()
  })
  it('keeps the saved search conditions separate for each account', async () => {
    let page = await searchPage(1)
    await page.get('#paper-query').setValue('private-to-first-account')
    await page.get('[data-test="add-keyword"]').trigger('click'); page.unmount()
    page = await searchPage(2)
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(0)
    await page.get('#paper-query').setValue('second account'); page.unmount()
    page = await searchPage(1)
    expect(page.get('[data-test="keyword-chip"]').text()).toContain('private-to-first-account')
    expect((page.get('#paper-query').element as HTMLInputElement).value).toBe('')
    page.unmount()
  })
  it('keeps phrases intact, includes pending input, and preserves term modes', async () => {
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval augmented generation')
    await page.get('#keyword-mode').setValue('exact')
    await page.get('[data-test="add-keyword"]').trigger('click')
    await page.get('#keyword-mode').setValue('fuzzy')
    await page.get('#paper-query').setValue('multimodal')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('retrieval augmented generation / multimodal', 'auto', 10, 1, 'relevance', [{ text: 'retrieval augmented generation', match_mode: 'exact' }, { text: 'multimodal', match_mode: 'fuzzy' }])
    expect(page.text()).toContain('精准匹配')
    expect(page.text()).toContain('模糊匹配')
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(2)
    await page.get('button[aria-label="移除关键词：multimodal"]').trigger('click')
    await page.get('[data-test="clear-keywords"]').trigger('click')
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(0)
    page.unmount()
  })
  it('explains case-insensitive duplicate additions while retaining the existing matching mode', async () => {
    const page = await searchPage()
    await page.get('#keyword-mode').setValue('exact')
    await page.get('#paper-query').setValue('RAG'); await page.get('[data-test="add-keyword"]').trigger('click')
    await page.get('#keyword-mode').setValue('fuzzy')
    await page.get('#paper-query').setValue('rag'); await page.get('[data-test="add-keyword"]').trigger('click')
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(1)
    expect(page.get('[role="alert"]').text()).toContain('关键词已存在')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('RAG', 'auto', 10, 1, 'relevance', [{ text: 'RAG', match_mode: 'exact' }])
    page.unmount()
  })
  it('ignores IME Enter, rejects duplicate terms and enforces keyword limits', async () => {
    const page = await searchPage()
    const input = page.get('#paper-query')
    await input.setValue('中文短语')
    await input.trigger('compositionstart'); await input.trigger('keydown', { key: 'Enter', isComposing: true })
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(0)
    await input.trigger('compositionend'); await input.trigger('keydown', { key: 'Enter' })
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(1)
    await input.setValue('中文短语'); await page.get('[data-test="add-keyword"]').trigger('click')
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(1)
    await page.get('[data-test="clear-keywords"]').trigger('click')
    for (let i = 0; i < 10; i++) { await input.setValue(`term${i}`); await page.get('[data-test="add-keyword"]').trigger('click') }
    await input.setValue('overflow'); await page.get('[data-test="add-keyword"]').trigger('click')
    expect(page.findAll('[data-test="keyword-chip"]')).toHaveLength(10)
    expect(page.text()).toContain('最多 10 个')
    await page.get('[data-test="clear-keywords"]').trigger('click')
    await input.setValue('a'.repeat(300)); await page.get('[data-test="add-keyword"]').trigger('click')
    await input.setValue('b'.repeat(198)); await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).not.toHaveBeenCalled()
    expect(page.text()).toContain('500')
    page.unmount()
  })
  it('invalidates pagination on keyword edits and pins Crossref across pages', async () => {
    const base = { contract_version: 1 as const, query: 'retrieval', requested_source: 'auto' as const, used_source: 'crossref', papers: [], page_size: 10, total: 35, has_next: true, sort: 'citations' as const }
    vi.mocked(api.papers.search).mockResolvedValueOnce({ ...base, page: 1 }).mockResolvedValueOnce({ ...base, page: 2 }).mockResolvedValueOnce({ ...base, page: 1 })
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval'); await page.get('#search-sort').setValue('citations')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(page.text()).toContain('不保证')
    expect(page.text()).toContain('DOI')
    await page.get('[data-test="next-page"]').trigger('click'); await flushPromises()
    await page.findAll('button').find(button => button.text() === '上一页')!.trigger('click'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('retrieval', 'crossref', 10, 1, 'citations', [{ text: 'retrieval', match_mode: 'fuzzy' }])
    await page.get('button[aria-label="移除关键词：retrieval"]').trigger('click')
    expect(page.get('[data-test="next-page"]').attributes('disabled')).toBeDefined()
    page.unmount()
  })
  it('blocks Crossref searches with exact terms rather than changing matching requirements', async () => {
    const page = await searchPage()
    await page.get('#search-source').setValue('crossref')
    await page.get('#keyword-mode').setValue('exact')
    await page.get('#paper-query').setValue('exact phrase')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).not.toHaveBeenCalled()
    expect(page.text()).toContain('Crossref 不支持精确短语')
    page.unmount()
  })
  it('requests page two from the actual source and resets sorting to page one', async () => {
    vi.mocked(api.papers.search).mockResolvedValue({ contract_version: 1, query: 'retrieval', requested_source: 'auto', used_source: 'arxiv', papers: [paper], page: 1, page_size: 10, total: 35, has_next: true, sort: 'relevance' } as Awaited<ReturnType<typeof api.papers.search>>)
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(page.find('[data-test="next-page"]').exists(), 'Search must expose upstream pages').toBe(true)
    await page.get('[data-test="next-page"]').trigger('click'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('retrieval', 'arxiv', 10, 2, 'relevance', [{ text: 'retrieval', match_mode: 'fuzzy' }])
    await page.get('#search-sort').setValue('latest')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('retrieval', 'auto', 10, 1, 'latest', [{ text: 'retrieval', match_mode: 'fuzzy' }])
    page.unmount()
  })
  it('keeps the fallback provider when returning to page one', async () => {
    const base = { contract_version: 1 as const, query: 'retrieval', requested_source: 'auto' as const, used_source: 'openalex', papers: [paper], page_size: 10, total: 35, has_next: true, sort: 'relevance' as const }
    vi.mocked(api.papers.search).mockResolvedValueOnce({ ...base, page: 1 }).mockResolvedValueOnce({ ...base, page: 2 }).mockResolvedValueOnce({ ...base, page: 1 })
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval'); await page.get('form').trigger('submit'); await flushPromises()
    await page.get('[data-test="next-page"]').trigger('click'); await flushPromises()
    await page.findAll('button').find(button => button.text() === '上一页')!.trigger('click'); await flushPromises()
    expect(api.papers.search).toHaveBeenLastCalledWith('retrieval', 'openalex', 10, 1, 'relevance', [{ text: 'retrieval', match_mode: 'fuzzy' }])
    page.unmount()
  })
  it('explains Chinese query matching and displays an unavailable fallback instead of a silent zero', async () => {
    vi.mocked(api.papers.search).mockResolvedValueOnce({ contract_version: 1, query: '多模态论文', requested_source: 'auto', used_source: 'arxiv', papers: [], warnings: [{ source: 'openalex', code: 'rate_limited', message: 'OpenAlex 请求受到限流，请稍后重试。' }] } as Awaited<ReturnType<typeof api.papers.search>>)
    const page = await searchPage()
    await page.get('#paper-query').setValue('多模态论文')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(page.text()).toContain('multimodal')
    expect(page.text()).toContain('OpenAlex 请求受到限流')
    page.unmount()
  })
  it('searches the requested source and adds once to the selected collection', async () => {
    const page = await searchPage()
    await page.get('#paper-query').setValue(' retrieval ')
    await page.get('#search-source').setValue('arxiv')
    await page.get('#search-limit').setValue(10)
    await page.get('[data-test="paper-search-form"]').trigger('submit'); await flushPromises()
    expect(api.papers.search).toHaveBeenCalledWith('retrieval', 'arxiv', 10, 1, 'relevance', [{ text: 'retrieval', match_mode: 'fuzzy' }])
    expect(page.text()).toContain('Evidence retrieval')
    await page.get('#target-collection').setValue('7')
    await page.get('[data-test="add-search-paper"]').trigger('click'); await flushPromises()
    expect(api.collections.addPaper).toHaveBeenCalledWith(7, paper)
    expect(page.get('[data-test="add-search-paper"]').attributes('disabled')).toBeDefined()
    expect(api.collections.addPaper).toHaveBeenCalledOnce()
    page.unmount()
  })
  it('retains previous results on upstream errors and suppresses unsafe links', async () => {
    vi.mocked(api.papers.search).mockResolvedValueOnce({ contract_version: 1, query: 'retrieval', requested_source: 'auto', used_source: 'arxiv', papers: [{ ...paper, page_url: 'javascript:alert(1)' }] }).mockRejectedValueOnce(new Error('外部文献源暂时不可用'))
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval')
    await page.get('form').trigger('submit'); await flushPromises()
    expect(page.find('a[href^="javascript:"]').exists()).toBe(false)
    await page.get('form').trigger('submit'); await flushPromises()
    expect(page.text()).toContain(paper.title)
    expect(page.get('[role="alert"]').text()).toContain('外部文献源')
    page.unmount()
  })
  it('does not overlap searches and ignores a result after leaving the page', async () => {
    let finish!: (value: Awaited<ReturnType<typeof api.papers.search>>) => void
    vi.mocked(api.papers.search).mockImplementation(() => new Promise(resolve => { finish = resolve }))
    const page = await searchPage()
    await page.get('#paper-query').setValue('retrieval')
    await page.get('form').trigger('submit'); await page.get('form').trigger('submit')
    expect(api.papers.search).toHaveBeenCalledOnce()
    page.unmount()
    finish({ contract_version: 1, query: 'retrieval', requested_source: 'auto', used_source: 'arxiv', papers: [paper] })
    await flushPromises()
  })
  it('edits only the owned collection membership while preserving all note drafts', async () => {
    const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/collections/:id', component: CollectionDetailView }, { path: '/collections', component: { template: '<div />' } }, { path: '/research/new', component: { template: '<div />' } }] })
    await router.push('/collections/7')
    const page = mount(CollectionDetailView, { global: { plugins: [router] } }); await flushPromises()
    await page.get('#overall-note').setValue('Unsaved notebook draft')
    await page.get('#paper-note-21').setValue('Unsaved reading draft')
    const edit = page.find('[data-test="edit-paper-21"]')
    expect(edit.exists(), 'Each saved paper needs a personal metadata editor').toBe(true)
    await edit.trigger('click'); await flushPromises()
    expect(api.collections.paper).toHaveBeenCalledWith(7, 21)
    expect((page.get('#edit-paper-source').element as HTMLInputElement).readOnly).toBe(true)
    expect((page.get('#edit-paper-id').element as HTMLInputElement).readOnly).toBe(true)
    await page.get('#edit-paper-title').setValue('My edited title')
    await page.get('[data-test="paper-edit-form"]').trigger('submit'); await flushPromises()
    expect(api.collections.updatePaper).toHaveBeenCalledWith(7, 21, { ...paper, title: 'My edited title' })
    expect((page.get('#overall-note').element as HTMLTextAreaElement).value).toBe('Unsaved notebook draft')
    expect((page.get('#paper-note-21').element as HTMLTextAreaElement).value).toBe('Unsaved reading draft')
    expect(page.text()).toContain('My edited title')
    page.unmount()
  })
})
